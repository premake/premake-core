local p = premake
local suite = test.declare("vstudio_sln2026_configurations")
local sln2026 = p.vstudio.sln2026


function suite.setup()
	p.action.set("vs2026")
end


local function prepare(wks)
	wks = test.getWorkspace(wks)
	sln2026.configurations(wks)
end


function suite.solution_header()
	sln2026.solution()

	test.capture [[
<Solution Description="Visual Studio slnx file generated by Premake" Version="1.4">
	]]
end


function suite.default_configurations()
	local wks = workspace "MyWorkspace"

	prepare(wks)

	test.capture [[
<Configurations>
</Configurations>
	]]
end


function suite.multiple_configurations()
	local wks = workspace "MyWorkspace"

	configurations { "Debug", "Release" }

	prepare(wks)

	test.capture [[
<Configurations>
	<BuildType Name="Debug" />
	<BuildType Name="Release" />
	<Platform Name="Win32" />
</Configurations>
	]]
end


function suite.default_platforms()
	local wks = workspace "MyWorkspace"

	prepare(wks)

	test.capture [[
<Configurations>
</Configurations>
	]]
end


function suite.multiple_platforms()
	local wks = workspace "MyWorkspace"

	configurations { "Debug" }
	platforms { "x86", "x64" }

	prepare(wks)

	test.capture [[
<Configurations>
	<BuildType Name="Debug" />
	<Platform Name="x64" />
	<Platform Name="Win32" />
</Configurations>
	]]
end


function suite.default_configuration()
	local wks = workspace "MyWorkspace"

	configurations { "Debug", "Release" }
	defaultconfiguration "Release"

	prepare(wks)

	test.capture [[
